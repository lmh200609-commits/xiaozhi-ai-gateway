def seed_stories():
    print(f"[*] Starting bedtime stories seeding into '{ZONE_NAME}' ({ZONE_ID})...")
    with knowledge_store.get_conn() as conn:
        c = conn.cursor()
        existing_titles = set(r[0] for r in c.execute("SELECT title FROM documents WHERE zone_id = ?", (ZONE_ID,)).fetchall())

    added_count = 0
    for item in BEDTIME_STORIES:
        title = item["doc_data"]["title"]
        if title in existing_titles:
            print(f"[=] Story already exists: '{title}', skipping.")
            continue
        print(f"[+] Adding bedtime story: '{title}'...")
        doc_id = knowledge_store.add_structured_document(
            doc_data=item["doc_data"],
            file_name=item["file_name"],
            file_type="md",
            zone_id=ZONE_ID,
            zone_name=ZONE_NAME
        )
        print(f"    Added doc_id: {doc_id}")
        added_count += 1

    print(f"[OK] Bedtime stories seeding complete! Added {added_count} new story archives.")

if __name__ == "__main__":
    seed_stories()
